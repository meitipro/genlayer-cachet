import localFont from "next/font/local";

import ThemeSync from "@/components/ThemeSync";
import { WalletProvider } from "@/components/wallet";
import Cursor from "@/components/cine/Cursor";
import { ORIGIN } from "@/lib/chain";

import "./globals.css";
