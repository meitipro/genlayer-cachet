export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en" className={`${sans.variable} ${mono.variable}`} suppressHydrationWarning>
      <head>
        {/*
          The theme, RESOLVED before first paint.
          "System" is turned into an explicit light or dark here rather than
          being left as an absent attribute for a media query to handle. That
          keeps the dark palette defined exactly once in globals.css: a media
          query cannot join a selector list, so the alternative is duplicating
          the whole token block, and a partial duplicate is what made "System"
          on a dark machine render light.
          Running in <head> also means a reader who chose light never sees a
          frame of dark first. Reading localStorage can throw outright when
          site data is blocked, hence the try - an unhandled error here would
          block the document.
        */}
        <script
          dangerouslySetInnerHTML={{
            __html:
              "try{var t=localStorage.getItem('cachet:theme');" +
              "var d=t==='system'" +
              "?(window.matchMedia('(prefers-color-scheme: light)').matches?'light':'dark')" +
              ":(t==='light'?'light':'dark');" +
              "document.documentElement.setAttribute('data-theme',d)}" +
              "catch(e){document.documentElement.setAttribute('data-theme','dark')}",
          }}
        />
        {/*
          Whether the entry animation plays, decided before the first frame for
          the same reason the theme is.

          The intro used to switch itself on inside an effect, so the real
          sequence was: paint the landing, hydrate, THEN drop the seal animation
          on top of a page the reader was already looking at. It read as the
          animation arriving late because it was arriving late - it is meant to
          be the first thing on screen, not an interruption of the second.

          The overlay is in the server HTML now, so it is in the first paint.
          This decides synchronously whether to keep it, and CSS does the
          hiding, which is what keeps the server and client markup identical
          and the hydration quiet. Marking it seen here rather than in the
          effect matters too: the flag has to be set before a second render can
          read it.
        */}
        <script
          dangerouslySetInnerHTML={{
            __html:
              "try{var s=sessionStorage.getItem('cachet:intro-seen')==='1';" +
              "var r=matchMedia('(prefers-reduced-motion:reduce)').matches;" +
              "if(s||r){document.documentElement.setAttribute('data-intro','skip')}" +
              "else{sessionStorage.setItem('cachet:intro-seen','1')}}" +
              "catch(e){}",
          }}
        />
      </head>
      {/* No chrome here on purpose. The two route groups bring their own: the
          cinematic route is a fixed full-viewport app, and everything else
          keeps the rule bar, header and footer. */}
      <body>
        {/*
          Global, because the rule it replaces is global.
          cinematic.css carries the handoff's `cursor:none !important` under
          `(hover:hover) and (pointer:fine)`, which is every desktop mouse on
          every page. In the handoff that is safe: the whole design is one
          page, and the custom cursor is always mounted. Here it would have
          left the docket, the forms and the docs with no pointer at all.
        */}
        <Cursor />
        {/*
          Global for the same reason as the cursor above. The boot script in
          <head> resolves the palette before the first frame and the dashboard
          toggle applies a deliberate change; this is the third case - the OS
          switching under a reader who chose "system" - and it has to work on
          every route, not only the one that happens to own the control.
        */}
        <ThemeSync />
        {/*
          One wallet state for the whole app.
          The landing's connect step and the dashboard's chip have to agree,
          and before this each component ran its own discovery: the bid panel
          could report an address while the header still offered Connect on
          the same screen.
        */}
        <WalletProvider>{children}</WalletProvider>
      </body>
    </html>
  );
}
